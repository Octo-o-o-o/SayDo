export function lines(parts) {
  return `${parts.filter((part) => part !== null).join("\n")}\n`;
}

export function metaComment(model) {
  return [
    "<!-- corpus:dry-run-meta",
    `generated_at: ${model.generatedAt}`,
    `source_tree_sha256: ${model.sourceTreeSha256}`,
    `authority_sha256: ${model.authoritySha256}`,
    `total: ${model.summary.total}`,
    `live: ${model.liveCount}`,
    `live_objects: ${model.liveObjectCount}`,
    `f1: ${model.f1Count}`,
    `simulations: ${model.simulationCount}`,
    `ctx: ${model.summary.ctxQuestions}`,
    "-->"
  ].join("\n");
}

function renderIdList(title, ids) {
  return [
    `### ${title}`,
    "",
    `共 ${ids.length} 条，全量列出，不抽样。`,
    "",
    ids.length ? ids.map((id) => `- \`${id}\``).join("\n") : "- （无）",
    ""
  ].join("\n");
}

