function issueSection(code) {
  const item = ISSUE_CODES[code];
  return [
    `### \`${code}\` ${item.title}`,
    "",
    `- 触发条件：${item.trigger}`,
    `- 标准补充物：${item.supplement}`,
    `- 最小字段：${item.minFields.map((field) => `\`${field}\``).join("、")}`,
    `- 验收门：${item.acceptance}`,
    `- 失败时安全降级：${item.degrade}`,
    ""
  ].join("\n");
}

export function renderP0Advice(row) {
  const fill = [];
  if (row.issueCodes.includes("DR-S3-SAFETY-CAPSULE")) {
    fill.push("逐题填写 effect 对象、动作、影响、回滚点和强认证主体；禁止语音批准");
  }
  if (row.issueCodes.includes("DR-F4-RESCOPE")) {
    fill.push("逐题写出越权条款、拒绝理由和允许的安全收缩范围");
  }
  if (row.issueCodes.includes("DR-F3-PLAN-ONLY")) {
    fill.push("逐题列出当前缺口与人工交接人，计划不得冒充已执行 effect");
  }
  if (row.issueCodes.includes("DR-EXTERNAL-CONNECTOR")) {
    fill.push(`逐对象填写 locator 形状、最小 scope 和只读探测：${row.liveSourceKinds.join("、") || "-"}`);
  }
  if (row.issueCodes.includes("DR-USER-INPUT")) {
    fill.push("逐题填写 USER 工件类型与必填字段，不写入 CTX fixture");
  }
  if (row.issueCodes.includes("DR-LONG-RUN-CHECKPOINT")) {
    fill.push("逐题填写 run_id、checkpoint_digest、idempotency_keys 与停止条件");
  }
  if (row.issueCodes.includes("DR-MULTITOOL-RECOVERY")) {
    fill.push(`逐工具登记 DAG 与 partial-effect ledger：${row.tools.join("、") || "-"}`);
  }
  if (row.issueCodes.includes("DR-CTX-AUTHORITY-STALE")) {
    fill.push("逐题填写 manifest_digest、valid_until、authority_order 与 unknown_on_failure");
  }
  return [
    `### \`${row.id}\``,
    "",
    `- 源标签：${row.F}/${row.S}；${row.tags}；上下文 \`${row.context}\`；工具 \`${row.toolsText}\``,
    `- 角色与情境：${cell(row.situation)}`,
    `- 潜在客户提问：${cell(row.question)}`,
    `- 对应目的：${cell(row.purpose)}`,
    `- 冷启动 DR1：\`${row.dr1}\`；充分前置 DR2：\`${row.dr2}\`；理论结论：${row.theoretical}`,
    `- 静态扰动：\`${row.perturbation}\`；期望恢复：\`${row.recovery}\`；扰动证据：\`${row.evidenceStatus}\``,
    `- issue code：\`${row.issueCodeText}\``,
    `- 必须补的通用模板：${row.issueCodes.map((code) => `\`${code}\``).join("、") || "-"}`,
    `- 必须逐题填写：${fill.join("；") || "按对应 issue code 最小字段补齐"}`,
    "- 验收门：不得生成真实外部消费，不得伪造授权收据，不得把预览当成已执行；`ready_for_review` 不等于交付",
    "- 安全降级：拒绝或收缩越权与未授权 effect，只保留资料整理、计划或人工决策辅助",
    "- 本条补充建议是静态设计，不是已经跑过的真实恢复实验",
    ""
  ].join("\n");
}

export function renderP1GroupSection(model, groupId) {
  const ids = model.summary.p1Groups[groupId] ?? [];
  const meta = P1_GROUP_META[groupId];
  const rows = model.judgments.filter((row) => ids.includes(row.id));
  const shared = new Set();
  for (const row of rows) for (const code of row.issueCodes) shared.add(code);
  return [
    `### ${meta.title}`,
    "",
    `${meta.pattern}`,
    "",
    `- 覆盖 ID（${ids.length}）：${idList(ids)}`,
    `- 共享模板：${[...shared].map((code) => `\`${code}\``).join("、") || "-"}`,
    "- 通用可复用：checkpoint/租约字段、单工具 partial result 字段、replay oracle 骨架",
    "- 必须逐题填写：LIVE 对象、USER 字段、停止条件、失败工具和允许的降级产物",
    "",
    "| ID | F/S | 上下文 | DR1 | 扰动 | 扰动证据 | issue code | 逐题必填要点 |",
    "|---|---|---|---|---|---|---|---|",
    ...rows.map((row) => {
      const point = [
        row.needsUser ? "USER schema" : null,
        row.hasExternalConnector ? "connector preflight" : null,
        (row.D === "D4" || row.H === "H4" || row.R === "R4") ? "checkpoint/租约" : null,
        (row.K === "K3" || row.K === "K4") ? "partial result" : null,
        row.F === "F1" ? "F1 失败变体" : null,
        row.F === "F3" ? "plan/handoff" : null,
        row.issueCodes.includes("DR-CTX-AUTHORITY-STALE") ? "CTX digest" : null
      ].filter(Boolean).join("、") || "按 issue code 最小字段";
      return `| ${row.id} | ${row.F}/${row.S} | ${cell(row.context)} | ${row.dr1} | ${row.perturbation} | ${row.evidenceStatus} | ${cell(row.issueCodeText)} | ${cell(point)} |`;
    }),
    ""
  ].join("\n");
}

