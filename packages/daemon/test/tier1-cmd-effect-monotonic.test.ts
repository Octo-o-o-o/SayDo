const emptyRegistry = { packageScripts: [], justfileTasks: [] };

async function gateOf(command: string) {
  const effect = commandToEffect(command);
  let confirms = 0;
  const decision = await decideCommand(
    { taskId: "r8b1", seq: 1, command, effect },
    {
      registry: emptyRegistry,
      stepConfirm: async () => {
        confirms += 1;
        return true;
      },
      approvalTimeoutMs: 2_000
    }
  );
  return { effect, decision, confirms };
}

function idx(kind: string): number {
  return RISK_ORDER.indexOf(kind);
}

// 每条命令的 4 种变体:原样 / 首空格插 `\<换行>` / 前置 `echo "'" && ` /
// 命令头包成 `"/bin/${PWD:+.}/<head>"`(rereview-8 反例形态)。
function variantsOf(c: string): string[] {
  const wrapped = c.replace(/\S+/, (h) => `"/bin/\${PWD:+.}/${h}"`);
  return [
    c,
    c.includes(" ") ? c.replace(" ", " \\\n") : c,
    `echo "'" && ${c}`,
    wrapped
  ];
}

describe("B8 rereview-8 动态命令头反例(legacy-classifier-floor)", () => {
  it("原反例与续行变体回 S3", () => {
    const cases: Array<[string, string]> = [
      ['"/bin/${PWD:+.}/rm" -rf /tmp/saydo-review-example', "delete_data"], // rereview-8 原反例:HEAD S3,修复前候选 install_dependency/S2
      ['"/bin/${PWD:+.}/rm" -rf \\\n/tmp/saydo-review-example', "delete_data"] // 续行变体
    ];
    for (const [command, kind] of cases) {
      const d = commandToEffect(command);
      expect(d.kind, command).toBe(kind);
      expect(computeRisk(d, {}).level, command).toBe("S3");
      expect(idx(d.kind)).toBeGreaterThanOrEqual(idx(legacyCommandToEffect(command).kind));
    }
  });

  it("动态命令头变体:判定不低于 HEAD 基线(HEAD 同等放宽的转 DF-TIER1-SHELL-01)", () => {
    const cases: Array<[string, string]> = [
      ['"$(command -v rm)" -rf /tmp/x', "install_dependency"], // HEAD 同判 S2:绕过在 HEAD 同样存在,转 DF-TIER1-SHELL-01
      ["${RM:-rm} -rf /tmp/x", "install_dependency"], // 同上
      ['/bin/r"m" -rf /tmp/x', "delete_data"] // 候选经 POSIX 词归一化认出 rm,比 HEAD 严
    ];
    for (const [command, kind] of cases) {
      const d = commandToEffect(command);
      expect(d.kind, command).toBe(kind);
      expect(idx(d.kind), command).toBeGreaterThanOrEqual(idx(legacyCommandToEffect(command).kind));
    }
  });

  it("整链 decide:原反例 deny 零确认", async () => {
    const { effect, decision, confirms } = await gateOf('"/bin/${PWD:+.}/rm" -rf /tmp/saydo-review-example');
    expect(effect.kind).toBe("delete_data");
    expect(decision.permission).toBe("deny");
    expect(decision.risk).toBe("S3");
    expect(confirms).toBe(0);
  });
});

describe("B8 单调性质:候选判定逐点不低于 HEAD(90e0777)", () => {
  it("legacyCommandToEffect 对语料原样命令的判定与 HEAD 快照逐位一致", () => {
    const drift: string[] = [];
    for (const [i, c] of CORPUS.entries()) {
      const d = legacyCommandToEffect(c);
      const [k, t] = LEGACY_SNAPSHOT[i]!;
      if (d.kind !== k || (d.touchesSensitiveData === true ? 1 : 0) !== t) {
        drift.push(`${JSON.stringify(c)} got ${d.kind}/${d.touchesSensitiveData === true ? 1 : 0} want ${k}/${t}`);
      }
    }
    expect(drift).toEqual([]);
  });

  it("语料 x 4 变体:commandToEffect(v) 不低于 legacyCommandToEffect(v)", () => {
    const violations: string[] = [];
    for (const c of CORPUS) {
      for (const v of variantsOf(c)) {
        const cand = commandToEffect(v);
        const base = legacyCommandToEffect(v);
        if (idx(cand.kind) < idx(base.kind)) {
          violations.push(`${JSON.stringify(v)} candidate=${cand.kind} legacy=${base.kind}`);
        }
        if (base.touchesSensitiveData && !cand.touchesSensitiveData) {
          violations.push(`${JSON.stringify(v)} lost touchesSensitiveData`);
        }
      }
    }
    expect(violations).toEqual([]);
  });
});

